//! Terminate the actual PostgreSQL publication session after its first ref write.
use super::*;

pub(super) async fn reject_interrupted_batch(
    database: &str,
    repository: &str,
    checkout: &Path,
    previous: &str,
) {
    let pool = sqlx::postgres::PgPoolOptions::new()
        .max_connections(2)
        .connect(database)
        .await
        .unwrap();
    let nonce = chrono::Utc::now().timestamp_nanos_opt().unwrap();
    let function = format!("atomic_git_loss_{}_{}", std::process::id(), nonce);
    let marker = i32::try_from(nonce.checked_rem(i64::from(i32::MAX)).unwrap()).unwrap();
    // All interpolated identifiers/literals are generated by this fixture.
    assert!(
        repository
            .bytes()
            .all(|byte| byte.is_ascii_alphanumeric() || b"/-".contains(&byte))
    );
    sqlx::raw_sql(sqlx::AssertSqlSafe(format!(
        "CREATE FUNCTION public.{function}() RETURNS trigger LANGUAGE plpgsql AS $$ BEGIN
         PERFORM pg_advisory_xact_lock(174892, {marker}); PERFORM pg_sleep(30); RETURN NEW; END $$;
         CREATE TRIGGER {function} BEFORE INSERT ON public.shardline_hub_refs
         FOR EACH ROW WHEN (NEW.repo_id = '{repository}' AND NEW.ref_name = 'peer')
         EXECUTE FUNCTION public.{function}();"
    )))
    .execute(&pool)
    .await
    .unwrap();
    let directory = checkout.to_owned();
    let pushing = tokio::spawn(async move {
        git(
            &directory,
            &["push", "--atomic", "origin", "HEAD:main", "HEAD:peer"],
        )
        .await
    });
    let mut backend = None;
    for _ in 0..250 {
        backend = sqlx::query_scalar::<_, i32>(
            "SELECT activity.pid FROM pg_locks locks JOIN pg_stat_activity activity ON activity.pid = locks.pid
             WHERE locks.locktype = 'advisory' AND locks.classid = 174892
               AND locks.objid::bigint = $1 AND locks.objsubid = 2 AND locks.granted
               AND activity.wait_event = 'PgSleep'"
        ).bind(i64::from(marker)).fetch_optional(&pool).await.unwrap();
        if backend.is_some() {
            break;
        }
        if pushing.is_finished() {
            break;
        }
        tokio::time::sleep(std::time::Duration::from_millis(20)).await;
    }
    if let Some(backend) = backend {
        let terminated: bool = sqlx::query_scalar("SELECT pg_terminate_backend($1)")
            .bind(backend)
            .fetch_one(&pool)
            .await
            .unwrap();
        assert!(terminated);
    }
    let output = pushing.await.unwrap();
    sqlx::raw_sql(sqlx::AssertSqlSafe(format!(
        "DROP TRIGGER {function} ON public.shardline_hub_refs; DROP FUNCTION public.{function}();"
    )))
    .execute(&pool)
    .await
    .unwrap();
    assert!(
        backend.is_some(),
        "native push never reached the observed second-ref transaction boundary"
    );
    assert!(!output.status.success());
    let trace = String::from_utf8_lossy(&output.stderr);
    assert!(trace.contains("ng refs/heads/main"), "{trace}");
    assert!(trace.contains("ng refs/heads/peer"), "{trace}");
    for reference in ["refs/heads/main", "refs/heads/peer"] {
        let advertised = success(checkout, &["ls-remote", "origin", reference]).await;
        assert_eq!(
            std::str::from_utf8(&advertised.stdout).unwrap(),
            format!("{previous}\t{reference}\n")
        );
    }
    let default: String =
        sqlx::query_scalar("SELECT default_branch FROM shardline_hub_repos WHERE repo_id = $1")
            .bind(repository)
            .fetch_one(&pool)
            .await
            .unwrap();
    assert_eq!(default, previous);
    pool.close().await;
}
